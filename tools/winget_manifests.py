"""The winget manifests for AI Voice Studio, and the rules they must satisfy.

winget (the Windows Package Manager) describes a package with **three YAML
documents** kept in the ``winget-pkgs`` repository under

    manifests/<first letter>/<Publisher>/<Package>/<Version>/

* ``<PackageIdentifier>.yaml`` - the version manifest,
* ``<PackageIdentifier>.installer.yaml`` - what to download and how to run it
  silently,
* ``<PackageIdentifier>.locale.<locale>.yaml`` - the human-readable metadata.

This module owns that description in one place so the generator
(``make_winget.py``), the checker (``winget_validate.py``) and the test suite
all agree on it, and so the version in the manifests cannot drift away from
``constants.APP_VERSION``.

It also carries a very small YAML writer and reader for exactly the subset
winget manifests use (maps, lists of maps, single-line scalars, comments).
The project deliberately does not depend on PyYAML: the manifests are
generated by us and read back by us, so a 100-line reader with no install
footprint is a better trade than a new runtime dependency.
"""

