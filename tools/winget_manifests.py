def release_tag(version: str) -> str:
    """``2026.3.7`` -> ``v2026.3.7`` (the Git tag the release pipeline uses)."""
    return "v" + str(version).strip()


def dashed_version(version: str) -> str:
    """``2026.3.7`` -> ``2026-3-7`` (dots are not allowed in file names)."""
    return str(version).strip().replace(".", "-")


def installer_filename(version: str, arch: str = "x64") -> str:
    """The installer name ``packaging/build.ps1`` produces."""
    return f"AI-Voice-Studio-v-{dashed_version(version)}-Setup-{arch}.exe"


def installer_url(version: str, arch: str = "x64") -> str:
    """The *stable, versioned* download URL of that installer."""
    return (
        f"{RELEASES_URL}/download/{release_tag(version)}/"
        f"{installer_filename(version, arch)}"
    )


def manifest_dir(root: str, version: str) -> str:
    """The ``manifests/a/AnujSharma/AIVoiceStudio/<version>`` folder."""
    letter = PACKAGE_IDENTIFIER[0].lower()
    return os.path.join(
        root, "winget", "manifests", letter, "AnujSharma", "AIVoiceStudio",
        str(version),
    )


def installer_path(root: str, version: str, arch: str = "x64") -> str:
    """Where the built installer for this version lives (``dist/``)."""
    return os.path.join(root, "dist", installer_filename(version, arch))


def file_sha256(path: str) -> str:
    """Uppercase SHA256 of a file, the form winget requires."""
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().upper()


